// Cover tool for the Lipschitz argument on the phase-1 coset graph (untrusted planning tool).
// F(cell) = min(d1(cell) + 18, min over centres s of k_s + dist(s, cell)); centres come with their 16 symmetry images.
// Greedy mode: repeatedly take an uncovered cell of maximal d1 (F > B), make it a centre with assumed bound K,
// propagate, until every cell has F <= B. Prints the centres as move words (representatives a = eval(word)).
// Usage: cover B K [maxcentres]        (memory: F 2.2 GB + d1 mmap 2.2 GB)
#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>
#include <sys/mman.h>
#include <sys/stat.h>
#include <fcntl.h>
#include <time.h>
#include <omp.h>

#define NCELL 2217093120L
static int32_t *TE, *TC, *TS; static uint8_t *d1, *F; static long idCell;
static void *loadf(const char *f) { FILE *fp = fopen(f, "rb"); if (!fp) { perror(f); exit(1); } fseek(fp, 0, SEEK_END); size_t sz = ftell(fp); fseek(fp, 0, SEEK_SET);
  void *p = malloc(sz); if (fread(p, 1, sz, fp) != sz) { perror("read"); exit(1); } fclose(fp); return p; }
static inline long nxt(long i, int m) { long e = i / (2187L * 495), c = (i / 495) % 2187, s = i % 495;
  return ((long)TE[e * 18 + m] * 2187 + TC[c * 18 + m]) * 495 + TS[s * 18 + m]; }

// 16 symmetries of H as move maps: generated by y (muY), z2 (muZ), F-B mirror (muM)
static const int muY[18] = {0,1,2,15,16,17,3,4,5,9,10,11,6,7,8,12,13,14};
static const int muZ[18] = {9,10,11,12,13,14,6,7,8,0,1,2,3,4,5,15,16,17};
static int muM[18]; static int SYM[64][18]; static int nsym;
static int addsym(const int *s) { for (int k = 0; k < nsym; k++) if (!memcmp(SYM[k], s, sizeof(int) * 18)) return 0; memcpy(SYM[nsym++], s, sizeof(int) * 18); return 1; }
static void gen_syms(void) {
  static const int piF[6] = {0,1,5,3,4,2};
  for (int m = 0; m < 18; m++) muM[m] = 3 * piF[m / 3] + (2 - m % 3);
  int id[18]; for (int m = 0; m < 18; m++) id[m] = m; addsym(id);
  const int *gens[3] = {muY, muZ, muM};
  for (int k = 0; k < nsym; k++) for (int g = 0; g < 3; g++) { int c[18]; for (int m = 0; m < 18; m++) c[m] = gens[g][SYM[k][m]]; addsym(c); }
}
static long cell_of_word(const int *w, int n, const int *mu) { long c = idCell; for (int i = 0; i < n; i++) c = nxt(c, mu ? mu[w[i]] : w[i]); return c; }

// representative word of a cell: descend d1 to H; a = eval(inverse of descent path)
static int rep_word(long c, int *w) {
  int path[16], n = 0;
  while (d1[c] > 0) { int ok = 0; for (int m = 0; m < 18 && !ok; m++) { long c2 = nxt(c, m); if (d1[c2] == d1[c] - 1) { path[n++] = m; c = c2; ok = 1; } } if (!ok) { fprintf(stderr, "descent failed\n"); exit(1); } }
  for (int i = 0; i < n; i++) { int m = path[n - 1 - i]; w[i] = 3 * (m / 3) + (2 - m % 3); }
  return n;
}

// local propagation from new seeds (value k), radius-limited; frontiers as bitmaps over cells (277 MB each)
static uint64_t *cur, *nx;
#define NW ((NCELL + 63) / 64)
static void relax_from(long *seeds, int ns, int k, int B) {
  memset(cur, 0, NW * 8);
  long n = 0;
  for (int i = 0; i < ns; i++) if (F[seeds[i]] > k) { F[seeds[i]] = k; cur[seeds[i] >> 6] |= 1ULL << (seeds[i] & 63); n++; }
  for (int v = k; v < B && n; v++) {
    memset(nx, 0, NW * 8); n = 0;
    for (long wi = 0; wi < NW; wi++) { uint64_t w = cur[wi]; while (w) { int b = __builtin_ctzll(w); w &= w - 1; long c0 = wi * 64 + b;
      for (int m = 0; m < 18; m++) { long c = nxt(c0, m); if (F[c] > v + 1) { F[c] = v + 1; nx[c >> 6] |= 1ULL << (c & 63); n++; } } } }
    uint64_t *t = cur; cur = nx; nx = t;
  }
}

int main(int argc, char **argv) {
  int B = atoi(argv[1]), K = atoi(argv[2]); int maxc = argc > 3 ? atoi(argv[3]) : 1000;
  TE = loadf("/root/f28/TE.bin"); TC = loadf("/root/f28/TC.bin"); TS = loadf("/root/f28/TS.bin");
  { FILE *fi = fopen("/root/f28/I0.txt", "r"); if (fscanf(fi, "%ld", &idCell) != 1) return 2; fclose(fi); }
  { int fd = open("/root/inter/k1dist.bin", O_RDONLY); struct stat st; fstat(fd, &st);
    d1 = mmap(0, st.st_size, PROT_READ, MAP_SHARED, fd, 0); if (d1 == MAP_FAILED) { perror("mmap"); return 3; } }
  gen_syms(); printf("symmetries: %d\n", nsym);
  F = malloc(NCELL); if (!F) { perror("F"); return 4; }
  for (long c = 0; c < NCELL; c++) F[c] = d1[c] + 18;
  cur = malloc(NW * 8); nx = malloc(NW * 8);
  time_t t0 = time(0);
  int nc = 0;
  for (;;) {
    // histogram of uncovered by d1
    long unc[13] = {0}, tot = 0; long pick = -1; int pd = -1;
    for (long c = 0; c < NCELL; c++) if (F[c] > B) { unc[d1[c]]++; tot++; if (d1[c] > pd) { pd = d1[c]; pick = c; } }
    printf("centres %d  uncovered %ld  (d10 %ld d11 %ld d12 %ld)  t=%lds\n", nc, tot, unc[10], unc[11], unc[12], (long)(time(0) - t0)); fflush(stdout);
    if (!tot || nc >= maxc) break;
    int w[16]; int n = rep_word(pick, w);
    printf("CENTRE %d d1=%d word:", nc, d1[pick]); for (int i = 0; i < n; i++) printf(" %d", w[i]); printf("\n"); fflush(stdout);
    long seeds[64]; int ns = 0;
    for (int s = 0; s < nsym; s++) seeds[ns++] = cell_of_word(w, n, SYM[s]);
    if (seeds[0] != pick) { fprintf(stderr, "representative mismatch\n"); return 5; }
    relax_from(seeds, ns, K, B);
    nc++;
  }
  return 0;
}
